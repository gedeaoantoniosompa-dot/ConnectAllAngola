export function traduzir(idioma, chave, ...args) {
  const dicionario = translations[idioma] || translations.pt;
  const valor = dicionario[chave] ?? translations.pt[chave] ?? chave;
  return typeof valor === 'function' ? valor(...args) : valor;
}